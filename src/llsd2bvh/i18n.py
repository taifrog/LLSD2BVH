def tr(key: str, lang: str, **kwargs) -> str:
    l = lang if lang in TRANSLATIONS else DEFAULT
    d = TRANSLATIONS[l]
    # fallback to ja if missing
    fmt = d.get(key, TRANSLATIONS[DEFAULT].get(key, key))
    if kwargs:
        try:
            return fmt.format(**kwargs)
        except Exception:
            return fmt
    return fmt
